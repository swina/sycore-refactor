/** The model's factory CC table (a fresh copy), or null when the model has none. */
export function ccTemplateFor(id: PcTemplateId | null | undefined): VirtualCcMapping[] | null {
  const t = id ? CC_TEMPLATES[id] : undefined
  return t ? t.map(r => ({ ...r })) : null
}

/** Adds the model's CCs that `table` doesn't have yet (existing rows, names and order are kept). */
export function mergeCcTemplate(table: VirtualCcMapping[], template: VirtualCcMapping[]): VirtualCcMapping[] {
  const used = new Set(table.map(r => r.cc))
  return [...table, ...template.filter(r => !used.has(r.cc)).map(r => ({ ...r }))]
}
